#!/usr/bin/env python3
"""Render docs/BENCHMARKS.md from a compare_tools.py results file. Every number in the document
comes from the JSON; the prose states methodology and caveats only.

usage: make_benchmarks_md.py RESULTS.json [--out docs/BENCHMARKS.md]
"""
from __future__ import annotations

import argparse
import json
import os
import statistics
import sys

# The page head (banner and navigation); tools/gen_doc_assets.py --check compares it with its table.
DOC_HEAD = """<!-- Head written by tools/gen_doc_assets.py: edit its table, then run it. -->
<p align="center">
<img src="assets/banner-benchmarks.svg" alt="Benchmarks. What do time, memory and start-up cost, tool by tool?" width="880">
</p>

# Benchmarks

[Documentation](README.md) &nbsp;·&nbsp; Previous: [Leaderboard](LEADERBOARD.md) &nbsp;·&nbsp; Next: [Ranking quality](QUALITY.md)

<!-- End of head. -->
"""

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL_ORDER = ["scrutate", "rg", "grep", "git", "ugrep", "ack", "ag"]
LABEL = {"scrutate": "scrutate", "rg": "ripgrep", "grep": "GNU grep", "git": "git grep", "ugrep": "ugrep", "ack": "ack", "ag": "ag"}


def fmt_ms(v):
    return "-" if v is None else (f"{v:,.0f}" if v >= 100 else f"{v:.1f}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    ap.add_argument("--out", default=os.path.join(HERE, "..", "docs", "BENCHMARKS.md"))
    a = ap.parse_args()
    d = json.load(open(a.results))
    gv = (d["environment"]["tools"].get("grep") or {}).get("version") or ""
    LABEL["grep"] = "GNU grep" if "GNU grep" in gv else ("BSD grep" if "BSD grep" in gv else "grep")
    env = d["environment"]
    out = []
    w = out.append
    w(DOC_HEAD)
    w(f"Generated by `bench/make_benchmarks_md.py` from `{os.path.basename(a.results)}` "
      f"(written by `bench/compare_tools.py` on {env['date']}). Rerun both scripts to reproduce it; "
      "nothing is typed by hand.\n")
    w("## Environment\n")
    w(f"- Machine: {env['cpu']}, {env['cores']} logical cores, {env['mem_gb']} GB RAM, {env['platform']}")
    w(f"- Runs per cell: {d['runs']} (half that on the massive corpus); warm cache unless noted; "
      "median wall time of the whole process (start to exit); CPU time and peak RSS from each child's `wait4` rusage.")
    w("- Tools (absolute paths; shell aliases bypassed):")
    for k, v in env["tools"].items():
        if v.get("version"):
            note = f" ({v['note']})" if v.get("note") else ""
            w(f"  - {LABEL.get(k, k)}: `{v['version']}`{note}")
        else:
            w(f"  - {LABEL.get(k, k)}: **not available on this machine** (not benchmarked)")
    w("")
    w("## Corpora\n")
    w("| Corpus | Files | Lines | Size |")
    w("|---|---|---|---|")
    for name, c in d["corpora"].items():
        w(f"| {name} | {c['files']:,} | {c['lines']:,} | {c['bytes']/1e6:,.0f} MB |")
    w("")
    w("`small` is a copy of the networkx package (Python); `big` is 10 Python packages from a site-packages "
      "tree (fontTools, matplotlib, mypy, networkx, numpy, pandas, pydantic, pygments, reportlab, scipy); "
      "`massive` is eight copies of `big` (same bytes, eight times the files: a size test, not a diversity test).\n")

    # ---------------------------------------------------------------- text search tables
    rows = d["text_search"]
    corpora = list(dict.fromkeys(r["corpus"] for r in rows))
    queries = list(dict.fromkeys(r["query"] for r in rows))
    tools = [t for t in TOOL_ORDER if any(r["tool"] == t and r.get("status") == "ok" for r in rows)]
    w("## Engine A: text search (median wall time, ms, warm cache)\n")
    w("Lower is better. **bold** = fastest in the row. `n/a` = the tool cannot express the query; `≠` = the tool returned another "
      "number of matching lines (not comparable); the last column is the match count.\n")
    for c in corpora:
        w(f"### {c}\n")
        w("| Query | " + " | ".join(LABEL[t] for t in tools) + " | matches |")
        w("|---|" + "---|" * len(tools) + "---|")
        for q in queries:
            cells, best, n = {}, None, None
            for t in tools:
                r = next((x for x in rows if x["corpus"] == c and x["query"] == q and x["tool"] == t), None)
                if r is None or r.get("status") == "unsupported":
                    cells[t] = "n/a"
                elif r.get("status") != "ok":
                    cells[t] = "error"
                elif not r.get("agrees", True):
                    cells[t] = f"≠ ({r['matches']:,})"
                else:
                    cells[t] = r["wall_median_ms"]
                    n = r["matches"]
                    if best is None or r["wall_median_ms"] < best:
                        best = r["wall_median_ms"]
            def cell(t):
                v = cells[t]
                if isinstance(v, str):
                    return v
                s = fmt_ms(v)
                return f"**{s}**" if v == best else s
            w(f"| {q} | " + " | ".join(cell(t) for t in tools) + f" | {n:,} |" if n is not None else f"| {q} | " + " | ".join(cell(t) for t in tools) + " | - |")
        w("")
    # summary: wins and geometric mean ratio vs each tool
    w("### Summary across all comparable rows\n")
    w("| Tool | rows compared with scrutate | scrutate faster | scrutate slower | geometric mean of (tool time / scrutate time) |")
    w("|---|---|---|---|---|")
    for t in tools:
        if t == "scrutate":
            continue
        ratios = []
        for c in corpora:
            for q in queries:
                a_ = next((x for x in rows if x["corpus"] == c and x["query"] == q and x["tool"] == "scrutate" and x.get("status") == "ok" and x.get("agrees", True)), None)
                b_ = next((x for x in rows if x["corpus"] == c and x["query"] == q and x["tool"] == t and x.get("status") == "ok" and x.get("agrees", True)), None)
                if a_ and b_:
                    ratios.append(b_["wall_median_ms"] / a_["wall_median_ms"])
        if ratios:
            gm = statistics.geometric_mean(ratios)
            w(f"| {LABEL[t]} | {len(ratios)} | {sum(1 for r in ratios if r > 1)} | {sum(1 for r in ratios if r < 1)} | {gm:.2f}× |")
    w("")
    # CPU and memory
    w("## CPU time and peak memory (common literal query)\n")
    w("| Corpus | Tool | CPU s (user+sys, median) | peak RSS MB |")
    w("|---|---|---|---|")
    for c in corpora:
        for t in tools:
            r = next((x for x in rows if x["corpus"] == c and x["query"] == "common literal" and x["tool"] == t and x.get("status") == "ok"), None)
            if r:
                w(f"| {c} | {LABEL[t]} | {r['cpu_median_s']:.3f} | {r['maxrss_mb']:.1f} |")
    w("")
    # cold cache
    if any("cold_wall_ms" in r for r in rows):
        w("## Cold cache (one run after `echo 3 > /proc/sys/vm/drop_caches`, ms)\n")
        w("| Corpus | Query | " + " | ".join(LABEL[t] for t in tools) + " |")
        w("|---|---|" + "---|" * len(tools))
        for c in corpora:
            for q in ["common literal", "rare literal", "regex"]:
                vals = []
                for t in tools:
                    r = next((x for x in rows if x["corpus"] == c and x["query"] == q and x["tool"] == t and x.get("status") == "ok"), None)
                    vals.append(fmt_ms(r.get("cold_wall_ms")) if r else "n/a")
                w(f"| {c} | {q} | " + " | ".join(vals) + " |")
        w("")
        w("Cold-cache numbers are single runs, dominated by disk reads every tool shares: reported for completeness, not ranking.\n")
    # startup
    w("## Startup (a directory with one file, no match; median ms)\n")
    w("| Tool | startup median | min |")
    w("|---|---|---|")
    timed = [x for x in d["startup"] if "startup_median_ms" in x]
    for s in sorted(timed, key=lambda x: x["startup_median_ms"]):
        w(f"| {LABEL.get(s['tool'], s['tool'])} | {s['startup_median_ms']:.1f} | {s['startup_min_ms']:.1f} |")
    for s in d["startup"]:
        if "startup_median_ms" not in s:
            w(f"| {LABEL.get(s['tool'], s['tool'])} | wrong ({s['status']}) | |")
    w("")
    # concurrency
    rounds = sorted({x["rounds"] for x in d["concurrency"] if "rounds" in x})
    w("## Concurrency (4 identical searches at once, aggregate wall ms, common literal)\n")
    if rounds:
        w(f"Median over {' or '.join(map(str, rounds))} rounds. Each process writes its own file, and every round checks each output's "
          "line count against the reference; `wrong` = a tool whose output differed (not timed further).\n")
    w("| Corpus | " + " | ".join(LABEL[t] for t in tools) + " |")
    w("|---|" + "---|" * len(tools))
    for c in corpora:
        vals = []
        for t in tools:
            r = next((x for x in d["concurrency"] if x["corpus"] == c and x["tool"] == t), None)
            vals.append("n/a" if r is None else "wrong" if r.get("status") == "wrong" else fmt_ms(r["wall_ms"]))
        w(f"| {c} | " + " | ".join(vals) + " |")
    w("")
    # structural
    if d.get("structural"):
        w("## Structural search: every Python `function_definition` (tree-sitter), ms\n")
        w("| Corpus | Tool | matches | median wall ms | peak RSS MB |")
        w("|---|---|---|---|---|")
        for r in d["structural"]:
            if r.get("status", "ok") != "ok":
                w(f"| {r['corpus']} | {r['tool']} | {r['status']} | - | - |")
                continue
            w(f"| {r['corpus']} | {r['tool']} | {r['matches']:,} | {fmt_ms(r['wall_median_ms'])} | {r['maxrss_mb']:.0f} |")
        w("")
        same = all(r.get("agrees", True) for r in d["structural"])
        cached = any(r["tool"].startswith("scrutate") and "--no-cache" not in r.get("cmd", "--no-cache") for r in d["structural"])
        how = ("ast-grep parses every file with tree-sitter on each run; scrutate's `tsquery` ran with its capture cache "
               "(`.scrutate/tsquery/`) filled by earlier runs, so its timed runs parsed no file (this measurement has no "
               "parse-for-parse run, `--no-cache`). " if cached else
               "Both tools parse every file with tree-sitter on each run (scrutate's `tsquery` with `--no-cache`); ")
        w(how + "scrutate's `tsquery` and ast-grep's `scan --inline-rules` "
          "were given the same node kind and " + ("returned identical counts.\n" if same else "their counts DIFFER on at least one corpus.\n"))
    # index
    if d.get("index"):
        w("## Engine B: index build, size and query latency\n")
        w("| Corpus | Files | Lines | Corpus MB | Index build s (cold) | peak RSS MB | no-op update s | 1-file edit update s | Index MB | Index/corpus | ranked search p50 / p95 ms (in-process) | `scrutate search` whole process ms (warm / cold) |")
        w("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for r in d["index"]:
            p = f"{r['search_p50_ms']:.1f} / {r['search_p95_ms']:.1f}" if "search_p50_ms" in r else "-"
            proc = f"{r.get('search_process_median_ms', 0):.0f} / {fmt_ms(r.get('search_process_cold_ms'))}" if "search_process_median_ms" in r else "-"
            w(f"| {r['corpus']} | {r['files']:,} | {r['lines']:,} | {r['corpus_mb']:.0f} | {r['index_build_s']:.1f} | {r['index_build_maxrss_mb']:.0f} | {r['index_noop_s']:.2f} | {r['index_incremental_s']:.2f} | {r['index_mb']:.0f} | {r['index_ratio']:.2f}× | {p} | {proc} |")
        w("")
        w("No competitor here builds a persistent index, so these numbers have no comparison: they are the cost of the ranked, semantic and "
          "structural search the grep-class tools lack. Ranking quality is measured separately (docs/QUALITY.md).\n")
    w("## Caveats (read these)\n")
    env = d["environment"]
    if (env["tools"].get("ugrep") or {}).get("note"):
        w(f"- ugrep: {env['tools']['ugrep']['note']}.")
    missing = [LABEL[t] for t in TOOL_ORDER if not (env["tools"].get(t) or {}).get("version")]
    if missing:
        w(f"- Not available on this machine, so absent rather than estimated: {', '.join(missing)}.")
    w(f"- {env['cores']} logical cores. Multi-threaded tools (scrutate, ripgrep, ugrep, git grep) scale with cores; grep, ack and ag search one file at a time.")
    w("- The corpora are Python only: byte-level search cost does not depend on the language, but structural search and indexing figures do.")
    w("- Rows where scrutate is slower are in the tables like any other. docs/LEADERBOARD.md has the statistical comparison (at least 20 runs per tool, 30 unless every verdict holds at the first look; confidence intervals) on more corpora; this page adds memory, start-up, concurrency and index costs.")
    text = "\n".join(out) + "\n"
    with open(a.out, "w") as f:
        f.write(text)
    print(f"wrote {a.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
